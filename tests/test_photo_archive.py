"""Check persistent photo archiving, recovery and retention with isolated data."""
import io
import os
import shutil
import tempfile
import unittest
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path
from unittest.mock import MagicMock, patch

from dotenv import dotenv_values
from PIL import Image
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

import photo_archive
from photo_media import md5_file
import video_conversion
from test_sighting_edit import Form


@unittest.skipUnless(os.environ.get('CAMERATRAP_TEST_POSTGRES') == '1', 'Opt-in PostgreSQL tests')
class PhotoArchivePostgresTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.folder = Path(self.directory.name)
        config = dict(dotenv_values(Path(__file__).resolve().parent.parent / '.env'))
        self.database = create_engine(make_url(config['db_url']).set(password=None))
        self.addCleanup(self.database.dispose)
        self.conn = self.database.connect()
        self.addCleanup(self.conn.close)
        transaction = self.conn.begin()
        self.addCleanup(transaction.rollback)
        self.conn.execute(text('''CREATE TEMP TABLE sighting (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE,
            operator TEXT, institution TEXT, timestamp TIMESTAMPTZ, camtrap_id TEXT, scalp TEXT,
            wolf_number INTEGER, latitude DOUBLE PRECISION, longitude DOUBLE PRECISION, notes TEXT,
            pup_number INTEGER, anomaly TEXT
        ) ON COMMIT DROP'''))
        self.conn.execute(text('''CREATE TEMP TABLE media (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sighting_id INTEGER,
            original_file_name TEXT, new_file_name TEXT, file_content_md5 TEXT, image BYTEA,
            media_type TEXT DEFAULT 'video', preview_file_name TEXT, capture_metadata JSONB, converted_file_name TEXT
        ) ON COMMIT DROP'''))
        self.conn.execute(text('''CREATE TEMP TABLE fototrappole (
            codice TEXT, operator TEXT, tipo TEXT, nome TEXT, cognome TEXT, comune TEXT,
            provincia TEXT, regione TEXT, latitudine DOUBLE PRECISION, longitudine DOUBLE PRECISION
        ) ON COMMIT DROP'''))
        self.conn.execute(text("INSERT INTO fototrappole VALUES ('FT01','user','Camera','','','Torino','Torino','Piemonte',45,7)"))
        for table in ('photo_archive_transfers', 'photo_archive_downloads', 'video_conversions', 'archive_transfers', 'archive_downloads'):
            self.conn.execute(text(f'CREATE TEMP TABLE {table} (LIKE public.{table} INCLUDING ALL) ON COMMIT DROP'))
        for column in ('archive_filename', 'archive_md5'):
            self.conn.execute(text(f'ALTER TABLE photo_archive_transfers ADD COLUMN IF NOT EXISTS {column} TEXT'))
        connection = self.conn

        class TransactionEngine:
            @contextmanager
            def begin(self):
                with connection.begin_nested():
                    yield connection

            @contextmanager
            def connect(self):
                yield connection

        self.engine = TransactionEngine()
        config['log_file'] = str(self.folder / 'app.log')
        with patch('dotenv.dotenv_values', return_value=config):
            import main
        self.main = main
        self.account = dict(username='user', fullname='User', institution='Test', code='T', is_active=True, is_admin=False)
        for patcher in (
            patch.object(main, 'engine', self.engine), patch.object(main, 'get_user', return_value=self.account),
            patch.object(main, 'start_conversion_worker'), patch.object(main.app.logger, 'disabled', True),
            patch.dict(main.app.config, TESTING=True, UPLOAD_FOLDER=str(self.folder)),
            patch.dict(main.config, archive_storage='OF2/test_photos'),
            patch.object(main.camtrap_banner_decoder, 'extract_date_time', return_value={'date':'2026-11-18','time':'120000'}),
        ):
            patcher.start()
            self.addCleanup(patcher.stop)
        self.client = main.app.test_client()
        with self.client.session_transaction() as session:
            session['username'] = 'user'
        self.client.get(main.APP_ROOT + '/upload_camtrap_photo_form')
        with self.client.session_transaction() as session:
            token = session['photo_upload_csrf_token']
        data = io.BytesIO()
        Image.new('RGB', (200,100), 'white').save(data, 'JPEG')
        self.original = data.getvalue()
        response = self.client.post(main.APP_ROOT + '/upload_camtrap_photo', data={
            'csrf_token':token, 'photo':(io.BytesIO(self.original),'camera.jpg'),
        }, content_type='multipart/form-data')
        self.assertEqual(response.status_code, 200)
        form = Form(response.get_data(as_text=True))
        self.payload = {name: field.get('value','') for name, field in form.fields.items()}
        self.payload.update(code='TEST-PHOTO', camtrap_id='FT01', wolf_number='1', scalp='C1', latitude='45', longitude='7', note='Photo')
        self.save_url = main.APP_ROOT + '/save_info'

    def save(self):
        response = self.client.post(self.save_url, data=self.payload)
        self.assertEqual(response.status_code, 302)
        self.media = self.conn.execute(text('SELECT * FROM media')).mappings().one()
        self.source = self.folder / self.media['new_file_name']
        self.preview = self.folder / self.media['preview_file_name']
        self.converted = self.source.with_name(self.source.name + '.webp')
        self.remote = self.folder / 'remote' / self.converted.name
        self.remote.parent.mkdir(exist_ok=True)
        self.conn.execute(text('UPDATE photo_archive_transfers SET destination=:remote'), {'remote':str(self.remote)})
        self.status_url = self.main.APP_ROOT + '/photo_archive_status/' + str(self.media['id'])

    def job(self, download=False):
        table = 'photo_archive_downloads' if download else 'photo_archive_transfers'
        return self.conn.execute(text(f'SELECT * FROM {table}')).mappings().one()

    def binary(self):
        binary = shutil.which('rclone') or str(Path.home()/'.local/bin/rclone')
        if not Path(binary).is_file():
            self.skipTest('rclone not installed')
        return binary

    def cleanup(self, now=None, apply=True):
        return photo_archive.cleanup_local_photos(self.engine, self.folder, apply=apply, now=now,
            archive_retention=timedelta(hours=48), recovery_retention=timedelta(hours=24))

    def test_real_rclone_webp_archive_cleanup_and_recovery_preserve_metadata_and_preview(self):
        self.save()
        self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder, self.binary(), 30))
        self.assertEqual(self.job()['status'], 'completed')
        from photo_conversion import read_preserved_metadata, source_metadata
        self.assertEqual(self.remote.read_bytes(), self.converted.read_bytes())
        self.assertEqual(read_preserved_metadata(self.remote), source_metadata(self.source))
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertEqual(md5_file(self.remote), self.job()['archive_md5'])
        self.assertEqual(self.conn.execute(text('SELECT converted_file_name FROM media')).scalar(), self.converted.name)
        metadata = self.media['capture_metadata']
        self.assertEqual(metadata['initial_source'], 'ocr')
        self.conn.execute(text("UPDATE photo_archive_transfers SET finished_at=CURRENT_TIMESTAMP-INTERVAL '3 days'"))
        self.assertEqual(self.cleanup(apply=False)['eligible_files'], 2)
        self.assertTrue(self.source.exists())
        self.assertEqual(self.cleanup()['deleted_files'], 2)
        self.assertTrue(self.preview.exists())
        status = self.client.get(self.status_url).json
        self.assertIsNone(status['download_url'])
        headers={'X-CSRF-Token':status['restore_csrf_token']}
        for _ in range(2):
            self.assertEqual(self.client.post(status['restore_url'], headers=headers).status_code, 202)
        self.assertEqual(self.job(download=True)['attempts'], 0)
        self.assertEqual(self.cleanup()['deleted_files'], 0)
        self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder, self.binary(), 30, download=True))
        self.assertEqual(self.job(download=True)['status'], 'completed')
        self.assertFalse(self.source.exists())
        self.assertEqual(self.converted.read_bytes(), self.remote.read_bytes())
        recovered = self.job(download=True)['finished_at']
        self.assertEqual(self.cleanup(now=recovered+timedelta(hours=23))['deleted_files'], 0)
        self.assertEqual(self.cleanup(now=recovered+timedelta(hours=25))['deleted_files'], 1)
        self.assertTrue(self.preview.exists())
        self.assertEqual(self.conn.execute(text('SELECT COUNT(*) FROM media')).scalar(), 1)

    def test_photo_and_sighting_are_rolled_back_if_queue_insert_fails(self):
        with patch('photo_routes.enqueue_photo', side_effect=ValueError('bad archive')):
            response = self.client.post(self.save_url, data=self.payload)
        self.assertEqual(response.status_code, 400)
        self.assertEqual(self.conn.execute(text('SELECT COUNT(*) FROM sighting')).scalar(), 0)
        self.assertEqual(self.conn.execute(text('SELECT COUNT(*) FROM media')).scalar(), 0)

    def test_copy_failures_retry_then_stop_and_keep_local_photo(self):
        self.save()
        with patch('photo_archive.copy_verified_file', side_effect=OSError('network unavailable')), \
                patch('photo_archive.convert_photo', wraps=photo_archive.convert_photo) as convert:
            for attempt in range(1,4):
                self.conn.execute(text('UPDATE photo_archive_transfers SET next_attempt_at=CURRENT_TIMESTAMP'))
                self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder))
                self.assertEqual(self.job()['attempts'], attempt)
                self.assertEqual(self.job()['status'], 'failed' if attempt==3 else 'pending')
                self.assertFalse(photo_archive.process_one_photo(self.engine, self.folder))
            convert.assert_called_once()
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertTrue(self.preview.exists())
        self.assertEqual(self.cleanup(now=datetime.now(timezone.utc)+timedelta(days=10))['deleted_files'], 0)

    def test_conversion_failure_never_transfers_or_expires_original(self):
        self.save()
        with patch('photo_archive.convert_photo', side_effect=ValueError('metadata mismatch')), \
                patch('photo_archive.copy_verified_file') as copy:
            self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder))
            copy.assert_not_called()
        self.assertIsNone(self.job()['archive_md5'])
        self.assertIn('metadata mismatch', self.job()['last_error'])
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertEqual(self.cleanup(now=datetime.now(timezone.utc)+timedelta(days=10))['deleted_files'], 0)

    def test_recovery_retention_does_not_shorten_original_retention(self):
        self.save()
        self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder, self.binary(), 30))
        self.conn.execute(text("UPDATE photo_archive_transfers SET finished_at=CURRENT_TIMESTAMP-INTERVAL '26 hours'"))
        photo_archive.enqueue_photo_download(self.conn, self.media['id'])
        self.conn.execute(text("UPDATE photo_archive_downloads SET status='completed', finished_at=CURRENT_TIMESTAMP-INTERVAL '25 hours'"))
        self.assertEqual(self.cleanup()['deleted_files'], 1)
        self.assertTrue(self.source.exists())
        self.assertFalse(self.converted.exists())
        self.assertTrue(self.preview.exists())

    def test_interrupted_recovery_and_explicit_retry(self):
        self.save()
        # Existing original-photo archives remain recoverable after the upgrade.
        self.conn.execute(text("UPDATE photo_archive_transfers SET archive_filename=NULL, status='completed', finished_at=CURRENT_TIMESTAMP"))
        self.remote.write_bytes(self.original)
        self.source.unlink()
        photo_archive.enqueue_photo_download(self.conn, self.media['id'])
        self.conn.execute(text("UPDATE photo_archive_downloads SET status='processing', attempts=1"))
        photo_archive.recover_photo_jobs(self.conn)
        self.assertTrue(photo_archive.process_one_photo(self.engine, self.folder, self.binary(), 30, download=True))
        self.assertEqual(self.job(True)['status'], 'completed')
        self.assertEqual(self.job(True)['attempts'], 2)
        self.assertEqual(self.source.read_bytes(), self.original)
        self.source.unlink()
        self.conn.execute(text("UPDATE photo_archive_downloads SET status='failed', attempts=3"))
        photo_archive.enqueue_photo_download(self.conn, self.media['id'])
        self.assertEqual(self.job(True)['status'], 'pending')
        self.assertEqual(self.job(True)['attempts'], 0)

    def test_restore_requires_owner_and_csrf(self):
        self.save()
        self.conn.execute(text("UPDATE photo_archive_transfers SET status='completed', finished_at=CURRENT_TIMESTAMP"))
        self.source.unlink()
        status=self.client.get(self.status_url).json
        self.assertEqual(self.client.post(status['restore_url']).status_code, 400)
        self.account['username']='other'
        self.assertEqual(self.client.post(status['restore_url'], headers={'X-CSRF-Token':status['restore_csrf_token']}).status_code, 404)
        self.assertEqual(self.conn.execute(text('SELECT COUNT(*) FROM photo_archive_downloads')).scalar(), 0)

    def test_shared_worker_processes_photo_archive(self):
        self.save()
        guard=MagicMock()
        guard.execute.return_value.scalar.return_value=True
        @contextmanager
        def connect():
            yield guard
        self.engine.connect=connect
        with patch('photo_archive.copy_verified_file') as copy:
            video_conversion.run_worker(self.engine, self.folder, archive_storage='OF2/test_photos')
        copy.assert_called_once()
        self.assertEqual(self.job()['status'], 'completed')

    def test_cleanup_retains_modified_original_and_never_deletes_preview(self):
        self.save()
        self.conn.execute(text("UPDATE photo_archive_transfers SET status='completed', finished_at=CURRENT_TIMESTAMP-INTERVAL '3 days'"))
        self.source.write_bytes(b'new unarchived contents')
        self.assertEqual(self.cleanup()['deleted_files'], 0)
        self.assertTrue(self.source.exists())
        self.assertTrue(self.preview.exists())
